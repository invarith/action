"""This action's releases: the files in `release/`, if there are any, and the version
and notes the release workflow takes from them (release_notes.py)."""

import io
import json
import re
from contextlib import redirect_stdout
from pathlib import Path

import pytest

import bootstrap
import release_notes
from release_notes import NotARelease, notes, version

REPOSITORY = Path(__file__).resolve().parents[1]

CLI = """# This file was autogenerated by uv via the following command:
#    uv export --frozen --no-config --package invarith-cli
pydantic==2.14.3 \\
    --hash=sha256:{a}
    # via invarith-core
z3-solver==5.4.1.0 \\
    --hash=sha256:{b} \\
    --hash=sha256:{c}
""".format(a="a" * 64, b="b" * 64, c="c" * 64)

RUNTIME = """hypothesis==6.170.15 \\
    --hash=sha256:{d}
""".format(d="d" * 64)


@pytest.fixture
def release(tmp_path: Path) -> Path:
    directory = tmp_path / "release"
    directory.mkdir()
    (directory / "invarith.json").write_text(
        json.dumps(
            {
                "version": "0.6.0",
                "packages": {
                    "invarith_runtime-0.6.0-py3-none-any.whl": "1" * 64,
                    "invarith_cli-0.6.0-py3-none-any.whl": "2" * 64,
                },
            }
        )
    )
    (directory / "cli.txt").write_text(CLI)
    (directory / "runtime.txt").write_text(RUNTIME)
    return directory


def test_the_repository_s_release() -> None:
    """If `release/` is here, the bootstrapper reads it, every pinned package has a
    version and a hash, and none is an invarith package; the release workflow takes
    its version and notes from it."""
    directory = REPOSITORY / "release"
    if not directory.exists():
        assert version(directory) is None
        return
    named = bootstrap.read_release(directory)
    assert version(directory) == named.version
    for requirements in (named.cli_requirements, named.runtime_requirements):
        text = requirements.read_text()
        blocks = re.split(r"\n(?=[^\s#])", text)
        pinned = [b for b in blocks if re.match(r"[^\s#]", b)]
        assert pinned, f"{requirements.name} pins nothing"
        for block in pinned:
            assert re.match(r"[A-Za-z0-9][A-Za-z0-9._-]*==\S+", block), block
            assert "--hash=sha256:" in block, block
            assert not block.lower().startswith("invarith"), block
    assert f"invarith/action v{named.version} runs invarith" in notes(directory)


def test_the_version(release: Path) -> None:
    assert version(release) == "0.6.0"


def test_no_release(tmp_path: Path) -> None:
    assert version(tmp_path / "release") is None
    with pytest.raises(NotARelease, match=r"no release/invarith\.json"):
        notes(tmp_path / "release")


@pytest.mark.parametrize("given", ["v0.6.0", "0.6", "0.6.0-rc1", 6])
def test_a_version_that_isn_t_x_y_z(release: Path, given: object) -> None:
    named = release / "invarith.json"
    found = json.loads(named.read_text())
    found["version"] = given
    named.write_text(json.dumps(found))
    with pytest.raises(NotARelease, match=r"isn't X\.Y\.Z"):
        version(release)


def test_the_notes(release: Path) -> None:
    assert notes(release) == (
        "invarith/action v0.6.0 runs invarith 0.6.0: it downloads invarith's "
        "packages below, checks each against its SHA-256, and installs them with the "
        "third-party packages pinned below, each checked against its hashes.\n"
        "\n"
        "## invarith's packages\n"
        "\n"
        "| Package | SHA-256 |\n"
        "|---|---|\n"
        f"| `invarith_cli-0.6.0-py3-none-any.whl` | `{'2' * 64}` |\n"
        f"| `invarith_runtime-0.6.0-py3-none-any.whl` | `{'1' * 64}` |\n"
        "\n"
        "## Pinned for the CLI and the verifier\n"
        "\n"
        "| Package | Version |\n"
        "|---|---|\n"
        "| `pydantic` | `2.14.3` |\n"
        "| `z3-solver` | `5.4.1.0` |\n"
        "\n"
        "## Pinned for the Python harness runtime\n"
        "\n"
        "| Package | Version |\n"
        "|---|---|\n"
        "| `hypothesis` | `6.170.15` |\n"
    )


def test_the_command(
    release: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    monkeypatch.setattr(release_notes, "RELEASE", release)
    out = io.StringIO()
    with redirect_stdout(out):
        assert release_notes.main(["version"]) == 0
    assert out.getvalue() == "0.6.0\n"
    assert release_notes.main(["notes"]) == 0
    assert capsys.readouterr().out.startswith("invarith/action v0.6.0")
    assert release_notes.main(["publish"]) == 2
