def test_the_notes_with_the_typescript_runtime(release: Path) -> None:
    """The runtime's npm package is among invarith's packages, and the packages its
    lockfile pins are listed with the platforms they're for."""
    written = notes(with_typescript(release))
    assert f"| `invarith-typescript-runtime-0.6.0.tgz` | `{'3' * 64}` |" in written
    assert written.endswith(
        "## Pinned for the TypeScript runtime\n"
        "\n"
        "npm installs each one on the platforms it's for.\n"
        "\n"
        "| Package | Version | Platforms |\n"
        "|---|---|---|\n"
        "| `@esbuild/linux-x64` | `0.28.2` | linux x64 |\n"
        "| `tsx` | `4.23.15` | all |\n"
    )


def test_the_notes_with_the_java_tools(release: Path) -> None:
    """The Java tools' jars are among invarith's packages, and the notes say what
    third-party code they hold; a release without them says nothing of it."""
    written = notes(with_java(with_typescript(release)))
    assert f"| `invarith-maven-extension-0.6.0.jar` | `{'5' * 64}` |" in written
    assert f"| `invarith-runtime-0.6.0.jar` | `{'4' * 64}` |" in written
    assert "holds its one third-party dependency, Byte Buddy, shaded" in written


def test_the_command(
    release: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    monkeypatch.setattr(release_notes, "RELEASE", release)
    out = io.StringIO()
    with redirect_stdout(out):
        assert release_notes.main(["version"]) == 0
    assert out.getvalue() == "0.6.0\n"
    assert release_notes.main(["notes"]) == 0
    assert capsys.readouterr().out.startswith("invarith/action v0.6.0")
    assert release_notes.main(["publish"]) == 2
